import { expect, test } from './local-requests';
import { captureViewportProof } from './review-capture';
import { login, ownerEmail, shopLogin, shopAccountAction } from './helpers';

test('customer order history, detail, and cancellation are reflected in Admin', async ({ page, newObservedContext }) => {
  const shopContext = await newObservedContext({ baseURL: 'http://127.0.0.1:3003' });
  const shop = await shopContext.newPage();
  try {
    await shop.goto('/en/register');
    await shop.getByLabel('Username').fill('History Buyer');
    await shop.getByLabel('Email').fill('history-buyer@e2e.example');
    await shop.getByLabel('Password', { exact: true }).fill('HistoryBuyerPassword123!');
    await shop.getByRole('button', { name: 'Create account' }).click();
    await expect(shop).toHaveURL(/\/en\/account$/);
    await shop.goto('/en/products');
    await shop.getByRole('link', { name: /E2E Product/ }).click();
    await shop.getByRole('button', { name: 'Add to cart' }).click();
    await shop.getByRole('link', { name: 'Checkout', exact: true }).click();
    await shop.getByLabel('First name').fill('History');
    await shop.getByLabel('Last name').fill('Buyer');
    await shop.getByLabel('Phone').fill('+1-555-0117');
    await shop.getByLabel('Address line 1').fill('17 History Street');
    await shop.getByRole('textbox', { name: 'City', exact: true }).fill('San Francisco');
    await shop.getByLabel('State / province').fill('CA');
    await shop.getByLabel('Postal code').fill('94105');
    await shop.getByRole('combobox', { name: 'Country', exact: true }).selectOption({ label: 'United States' });
    await shop.getByRole('button', { name: 'Get shipping options' }).click();
    await shop.getByRole('radio', { name: /Free shipping/i }).check();
    await shop.getByRole('radio', { name: 'Manual payment' }).check();
    await shop.getByRole('button', { name: /^Pay /, exact: false }).click();
    await expect(shop).toHaveURL(/\/en\/checkout\/complete\?order=/);
    const orderId = new URL(shop.url()).searchParams.get('order');
    expect(orderId).toBeTruthy();
    await shopAccountAction(shop, 'en', 'orders');
    await expect(shop.getByRole('heading', { name: 'My orders' })).toBeVisible();
    await expect(shop.getByText('Pending', { exact: true }).first()).toBeVisible();
    await shop.getByRole('link', { name: /^View details/ }).filter({ visible: true }).click();
    await expect(shop.getByText('Pay manually.')).toBeVisible();
    await expect(shop.getByText(/Pay before/)).toBeVisible();
    await shop.getByRole('button', { name: 'Cancel order' }).click();
    await shop.getByRole('combobox', { name: 'Reason' }).selectOption('other');
    await shop.getByRole('textbox', { name: 'Other reason' }).fill('Please cancel this test purchase');
    await shop.getByRole('button', { name: 'Confirm cancellation' }).click();
    await expect(shop.getByText('Cancelled', { exact: true })).toBeVisible();
    await expect(shop.getByRole('button', { name: 'Cancel order' })).toHaveCount(0);
    await expect(shop.getByText('Pay manually.')).toHaveCount(0);
    await login(page, ownerEmail, 'FinalOwnerPassword123!');
    await page.goto(`/en/orders/${orderId}`);
    await expect(page.getByText('Please cancel this test purchase')).toBeVisible();
  } finally {
    await shopContext.close();
  }
});

test('Q Shop phone Sheet supports categories, language, account and cart without overflow', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  const checkWidth = async () => {
    const bounds = await page.getByRole('banner', { name: '' }).boundingBox();
    expect(bounds).not.toBeNull(); expect(bounds!.x).toBe(0); expect(bounds!.width).toBe(390);
    const image = await captureViewportProof(page);
    expect(image.readUInt32BE(16)).toBe(390);
  };
  await page.goto('http://127.0.0.1:3003/en');
  await expect(page.getByRole('heading', { name: 'Browse categories' })).toBeVisible();
  await checkWidth();
  const trigger = page.getByRole('button', { name: 'Open menu', exact: true });
  await trigger.click();
  const menu = page.getByRole('dialog', { name: /.+/ });
  await expect(menu.getByRole('link', { name: 'Login', exact: true })).toBeVisible();
  await expect(menu.getByRole('combobox', { name: 'Language', exact: true })).toHaveValue('en');
  await expect(menu.getByRole('link', { name: 'All products', exact: true })).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(menu).toBeHidden(); await expect(trigger).toBeFocused();
  await trigger.click();
  await menu.getByRole('link', { name: 'E2E Translated Category', exact: true }).click();
  await expect(page).toHaveURL('http://127.0.0.1:3003/en/categories/e2e-translated-category');
  await expect(menu).toBeHidden();
  await expect(page.getByRole('heading', { level: 1, name: 'E2E Translated Category', exact: true })).toBeVisible();
  const header = page.getByRole('banner', { name: '' });
  await header.getByRole('button', { name: 'Search products', exact: true }).click();
  const search = header.getByRole('search', { name: 'Search products', exact: true });
  await expect(search).toHaveAttribute('action', '/en/search');
  await search.getByRole('searchbox', { name: 'Search products', exact: true }).fill('E2E Localized Product');
  await search.getByRole('button', { name: 'Search', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'E2E Localized Product', exact: true })).toBeVisible();
  await checkWidth();
  await page.goto('http://127.0.0.1:3003/en/login');
  await shopLogin(page, { locale: 'en', email: 'history-buyer@e2e.example', password: 'HistoryBuyerPassword123!', expectedPath: '/en' });
  await page.goto('http://127.0.0.1:3003/en/cart');
  await expect(page.getByText('Your cart is empty', { exact: true })).toBeVisible();
  await expect(header.getByRole('button', { name: 'Cart (0)', exact: true })).toBeVisible();
  await checkWidth();
  await trigger.click();
  await menu.getByRole('link', { name: 'Account', exact: true }).click();
  await expect(page.getByRole('heading', { level: 1, name: 'My account', exact: true })).toBeVisible();
  await page.getByRole('main', { name: '' }).getByRole('link', { name: 'My orders', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'My orders' })).toBeVisible();
  await expect(page.getByRole('list', { name: 'My orders', exact: true }).getByText('Cancelled', { exact: true })).toBeVisible();
  await checkWidth();
  await trigger.click(); await menu.getByRole('button', { name: 'Logout', exact: true }).click();
  await expect(page).toHaveURL('http://127.0.0.1:3003/en');
});
