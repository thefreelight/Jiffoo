import { expect, test } from './local-requests'
import { login, ownerEmail } from './helpers'

test('create category and product translations, reopen and remove one translation', async ({ page }) => {
  await login(page, ownerEmail, 'FinalOwnerPassword123!')
  await page.goto('/en/products')
  await page.getByRole('main', { name: '' }).getByRole('link', { name: 'Categories', exact: true }).click()
  await page.getByRole('button', { name: 'Add category' }).click()
  await page.getByRole('textbox', { name: 'Name', exact: true }).fill('E2E Translated Category')
  await page.getByRole('textbox', { name: 'Slug' }).fill('e2e-translated-category')
  await page.getByRole('textbox', { name: 'Translated name (Simplified Chinese)' }).fill('测试分类')
  await page.getByRole('textbox', { name: 'Translated name (Traditional Chinese)' }).fill('測試分類')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByText('E2E Translated Category', { exact: true }).first()).toBeVisible()
  await page.getByRole('button', { name: 'Edit: E2E Translated Category' }).click()
  await expect(page.getByRole('textbox', { name: 'Translated name (Simplified Chinese)' })).toHaveValue('测试分类')
  await expect(page.getByRole('textbox', { name: 'Translated name (Traditional Chinese)' })).toHaveValue('測試分類')
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('link', { name: '← Products', exact: true }).click()

  await page.goto('/en/products/create')
  await page.getByLabel('Name', { exact: true }).first().fill('E2E Localized Product')
  await page.getByLabel('Category', { exact: true }).selectOption({ label: 'E2E Translated Category' })
  await page.getByRole('textbox', { name: 'Translated name (Simplified Chinese)' }).fill('测试商品')
  await page.getByRole('textbox', { name: 'Translated name (Traditional Chinese)' }).fill('測試商品')
  await page.getByLabel('Name', { exact: true }).nth(1).fill('Standard')
  await page.getByLabel('SKU', { exact: true }).fill('E2E-LOCALIZED')
  await page.getByLabel('Price', { exact: true }).fill('20')
  await page.getByLabel('Stock', { exact: true }).fill('5')
  await page.getByRole('button', { name: 'Create product' }).click()
  await expect(page).toHaveURL(/\/en\/products$/)
  await page.goto('/en/products/categories')
  await page.getByRole('button', { name: 'Delete: E2E Translated Category' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Delete', exact: true }).click()
  await expect(page.getByRole('alert').filter({ hasText: 'Remove products and child categories before deleting this category.' })).toHaveText('Remove products and child categories before deleting this category.')
  await expect(page.getByText('E2E Translated Category', { exact: true }).first()).toBeVisible()
  await page.goto('/en/products')
  await page.getByRole('link', { name: 'E2E Localized Product' }).first().click()
  await expect(page.getByRole('textbox', { name: 'Translated name (Simplified Chinese)' })).toHaveValue('测试商品')
  await expect(page.getByRole('textbox', { name: 'Translated name (Traditional Chinese)' })).toHaveValue('測試商品')
  await page.getByRole('textbox', { name: 'Translated name (Traditional Chinese)' }).fill('')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByText('Unsaved changes', { exact: true })).toHaveCount(0)
  await page.goto('/en/products')
  await page.getByRole('link', { name: 'E2E Localized Product' }).first().click()
  await expect(page.getByRole('textbox', { name: 'Translated name (Traditional Chinese)' })).toHaveValue('')
  await expect(page.getByRole('textbox', { name: 'Translated name (Simplified Chinese)' })).toHaveValue('测试商品')
})
