    await dialog.getByLabel('Name', { exact: true }).fill('E2E Customer'); await dialog.getByRole('button', { name: 'Save', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'E2E Customer', exact: true })).toBeVisible();
