import { expect, test } from './local-requests';
import { changedPassword, login, logout, originalPassword, ownerEmail } from './helpers';
import { captureStaffPage } from './staff-captures';

test('profile save guard and password change preserve this session and revoke the old password', async ({ page }) => {
  test.setTimeout(120000);
  await login(page, ownerEmail, originalPassword);
  await page.goto('/en/profile');
  await expect(page.getByRole('heading', { name: 'My account', exact: true })).toBeVisible();
  const originalName = await page.getByLabel('Name', { exact: true }).inputValue();
  await expect(page.getByRole('button', { name: 'Save', exact: true })).toBeDisabled();
  await captureStaffPage(page, 'profile', 'saved', '我的账户');
  await page.getByLabel('Name', { exact: true }).fill(originalName + ' Updated');
  await expect(page.getByText('Unsaved changes', { exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Overview', exact: true }).click();
  const guard = page.getByRole('alertdialog', { name: 'Unsaved changes', exact: true });
  await expect(guard).toBeVisible();
  await guard.getByRole('button', { name: 'Keep editing', exact: true }).click();
  await expect(page.getByLabel('Name', { exact: true })).toHaveValue(originalName + ' Updated');
  await page.getByRole('link', { name: 'Overview', exact: true }).click();
  await guard.getByRole('button', { name: 'Save and leave', exact: true }).click();
  await expect(page).toHaveURL(/\/en\/dashboard$/);
  await page.goto('/en/profile');
  await expect(page.getByLabel('Name', { exact: true })).toHaveValue(originalName + ' Updated');
  await expect(page.getByText(/^Saved ·/)).toBeVisible();
  await page.getByLabel('Name', { exact: true }).fill(originalName);
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Save', exact: true })).toBeDisabled();
  const security = page.getByRole('region', { name: 'Sign-in and security', exact: true });
  await security.getByRole('button', { name: 'Change password', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Change password', exact: true });
  await dialog.getByLabel('Current password', { exact: true }).fill('WrongPassword123!');
  await dialog.getByLabel('New password', { exact: true }).fill(changedPassword);
  await dialog.getByLabel('Re-enter new password', { exact: true }).fill(changedPassword);
  await dialog.getByRole('button', { name: 'Change password', exact: true }).click();
  await expect(dialog.getByText('The current password is incorrect. Please try again.', { exact: true })).toBeVisible();
  await expect(dialog.getByLabel('New password', { exact: true })).toHaveValue(changedPassword);
  await dialog.getByLabel('Current password', { exact: true }).fill(originalPassword);
  await dialog.getByRole('button', { name: 'Change password', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await page.reload();
  await expect(page.getByRole('heading', { name: 'My account', exact: true })).toBeVisible();
  await expect(page.getByRole('link', { name: 'Overview', exact: true })).toBeVisible();
  await logout(page);
  await page.getByPlaceholder('Enter your email').fill(ownerEmail);
  await page.getByPlaceholder('Enter your password').fill(originalPassword);
  await page.getByRole('button', { name: /sign in|authenticate/i }).click();
  await expect(page).toHaveURL(/\/en\/auth\/login/);
  await login(page);
});
